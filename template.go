// templateMain is the docs .templ component that renders each page.
const templateMain = "DocpagesMain"

// templatePackage is the package for docs .templ files.
const templatePackage = "docs"

// modulePath is the docpages module path.
const modulePath = "github.com/romshark/docpages"

// goSum is docpages' go.sum. A renderer's go.sum adds it, so a docs module
// needs no checksums of the modules that docpages requires.
//
//go:embed go.sum
var goSum []byte

// rendererPackage is the directory of the renderer's main package in a docs module.
// It exists only in the overlay of the build.
const rendererPackage = "docpagesrenderer"

// rendererMain returns the main package of a renderer that renders pages with
// templ DocpagesMain of the root package of module modPath.
func rendererMain(modPath string) []byte {
	return []byte(`// Code generated by docpages. DO NOT EDIT.

package main

import (
	"github.com/romshark/docpages"

	docs ` + strconv.Quote(modPath) + `
)

func main() { docpages.RenderMain(docs.DocpagesMain) }
`)
}

// templateFile is a docs .templ file.
type templateFile struct {
	name string // Path from the repository root, as "docs/template.templ".
	file *parser.TemplateFile
}

// readTemplates returns dir's .templ files from fsys. They must use package docs,
// and one must define templ DocpagesMain. Root-level docs take none because their
// .templ files belong to the repository like its other files.
func readTemplates(fsys fs.FS, dir string) ([]templateFile, error) {
	if dir == "." {
		return nil, nil
	}
	entries, err := fs.ReadDir(fsys, dir)
	if err != nil {
		return nil, err
	}
	var files []templateFile
	hasMain := false
	for _, e := range entries {
		if e.IsDir() || path.Ext(e.Name()) != ".templ" || strings.HasPrefix(e.Name(), ".") {
			continue
		}
		name := path.Join(dir, e.Name())
		src, err := fs.ReadFile(fsys, name)
		if err != nil {
			return nil, err
		}
		tf, err := parseTemplate(name, src)
		if err != nil {
			return nil, err
		}
		pkg := strings.TrimSpace(strings.TrimPrefix(
			strings.TrimSpace(tf.Package.Expression.Value), "package"))
		if pkg != templatePackage {
			pos := tf.Package.Expression.Range.From
			return nil, fmt.Errorf("%s:%d:%d: package %s, not package %s",
				name, pos.Line+1, pos.Col+1, pkg, templatePackage)
		}
		hasMain = hasMain || slices.ContainsFunc(tf.Nodes, isTemplateMain)
		files = append(files, templateFile{name: name, file: tf})
	}
	if len(files) > 0 && !hasMain {
		return nil, fmt.Errorf("%s: no templ %s(p docpages.Page) in the .templ files",
			dir, templateMain)
	}
	return files, nil
}

// parseTemplate returns the parsed .templ file named name from src.
func parseTemplate(name string, src []byte) (*parser.TemplateFile, error) {
	tf, err := parser.ParseString(string(src))
	if err != nil {
		var pe parse.ParseError
		if errors.As(err, &pe) {
			return nil, fmt.Errorf("%s:%d:%d: %s", name, pe.Pos.Line+1, pe.Pos.Col+1, pe.Msg)
		}
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	return tf, nil
}

// isTemplateMain reports whether n is templ DocpagesMain.
func isTemplateMain(n parser.TemplateFileNode) bool {
	t, ok := n.(*parser.HTMLTemplate)
	return ok && strings.HasPrefix(strings.TrimSpace(t.Expression.Value), templateMain+"(")
}

// RenderMain runs a renderer built from a docs directory's .templ files, with
// templ DocpagesMain passed as page. It reads docs selected by flags, renders
// them with page, and writes them to standard output for docpages.
func RenderMain(page func(Page) templ.Component) {
	if err := renderMain(os.Args[1:], os.Stdout, page); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// renderMain runs [RenderMain] with args, excluding the program name.
func renderMain(args []string, stdout io.Writer, page func(Page) templ.Component) error {
	flags := flag.NewFlagSet("renderer", flag.ContinueOnError)
	var o Options
	var served bool
	var reload string
	flags.StringVar(&o.Root, "root", ".", "Root directory of the repository")
	flags.StringVar(&o.Dir, "dir", ".", "Docs directory, relative to the root")
	flags.BoolVar(&served, "served", false, "Read the docs as Handler does")
	flags.StringVar(&reload, "reload", "", "State of the files that Handler reads")
	flags.BoolVar(&o.NoOffline, "no-offline", false, "Leave out offline viewing")
	if err := flags.Parse(args); err != nil {
		return err
	}
	s, err := readRepo(o, served)
	if err != nil {
		return err
	}
	s.page = page
	s.templateGlob = path.Join(s.main().dir, "*.templ")
	s.chrome.reload = reload
	pages, err := s.renderPages()
	if err != nil {
		return err
	}
	return gob.NewEncoder(stdout).Encode(pages)
}

// renderTemplates returns pages from s's .templ renderer by output path.
func (s *Site) renderTemplates() (map[string][]byte, error) {
	root, err := filepath.Abs(s.options.Root)
	if err != nil {
		return nil, err
	}
	program, err := buildRenderer(root, s.main().dir, s.templates, s.module)
	if err != nil {
		return nil, err
	}
	cmd := exec.Command(program, "-root", root, "-dir", s.options.Dir,
		"-served="+strconv.FormatBool(s.served != nil), "-reload", s.chrome.reload,
		"-no-offline="+strconv.FormatBool(s.options.NoOffline))
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		if msg := strings.TrimSpace(stderr.String()); msg != "" {
			return nil, errors.New(msg)
		}
		return nil, fmt.Errorf("%s: renderer: %w", s.main().dir, err)
	}
	var pages map[string][]byte
	if err := gob.NewDecoder(&stdout).Decode(&pages); err != nil {
		return nil, fmt.Errorf("%s: pages of the renderer: %w", s.main().dir, err)
	}
	return pages, nil
}

// renderers caches this process's renderers by directory, rebuilding only when
// sources change.
var renderers = struct {
	sync.Mutex
	built map[string]builtRenderer
}{built: make(map[string]builtRenderer)}

// builtRenderer is a renderer built by this process.
type builtRenderer struct {
	key     string // Hash of its sources.
	program string
}

// generated is a Go file produced by templ from a .templ file.
type generated struct {
	source    string // Path of the .templ file from the repository root.
	sourceMap *parser.SourceMap
}

// buildRenderer returns a renderer for templates, the .templ files of docs
// directory dir under root, whose module is mod. The go command builds it in mod.
// An overlay adds the Go of the templates and the renderer's main package,
// so the build writes nothing to the docs directory.
// A copy of go.mod makes the renderer use the running docpages.
func buildRenderer(
	root, dir string, templates []templateFile, mod *docsModule,
) (string, error) {
	// The go command matches overlay paths against its working directory with
	// symlinks resolved, as of macOS's /var in /private/var.
	modDir, err := filepath.EvalSymlinks(filepath.Join(root, filepath.FromSlash(dir)))
	if err != nil {
		return "", err
	}
	goMod, err := rendererModFile(mod, sourceDir(), buildVersion())
	if err != nil {
		return "", fmt.Errorf("%s: %w", dir, err)
	}
	build, err := rendererDir(root, dir)
	if err != nil {
		return "", err
	}
	files := map[string][]byte{
		"go.mod":  goMod,
		"go.sum":  joinSums(mod.goSum, goSum),
		"main.go": rendererMain(mod.path),
	}
	// replace maps paths in modDir to their content in build, or to "" for none.
	replace := map[string]string{
		filepath.Join(
			modDir, rendererPackage, "main.go",
		): filepath.Join(build, "main.go"),
	}
	// templ generate can leave the Go of a renamed or deleted .templ file.
	entries, err := os.ReadDir(modDir)
	if err != nil {
		return "", err
	}
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), "_templ.go") {
			replace[filepath.Join(modDir, e.Name())] = ""
		}
	}
	gens := make(map[string]generated)
	for _, t := range templates {
		var b bytes.Buffer
		out, err := generator.Generate(t.file, &b, generator.WithFileName(t.name))
		if err != nil {
			return "", fmt.Errorf("%s: %w", t.name, err)
		}
		name := strings.TrimSuffix(path.Base(t.name), ".templ") + "_templ.go"
		files["gen/"+name] = b.Bytes()
		// go build reports a file of the overlay by its path in build.
		gen := filepath.Join(build, "gen", name)
		gens[gen] = generated{source: t.name, sourceMap: out.SourceMap}
		replace[filepath.Join(modDir, name)] = gen
	}
	overlay, err := json.Marshal(struct{ Replace map[string]string }{replace})
	if err != nil {
		return "", err
	}
	files["overlay.json"] = overlay

	h := sha256.New()
	for _, name := range slices.Sorted(maps.Keys(files)) {
		_, _ = fmt.Fprintf(h, "%s\x00%d\x00%s", name, len(files[name]), files[name])
	}
	for _, name := range mod.goFiles {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
		if err != nil {
			return "", err
		}
		_, _ = fmt.Fprintf(h, "%s\x00%d\x00%s", name, len(data), data)
	}
	key := hex.EncodeToString(h.Sum(nil))

	renderers.Lock()
	defer renderers.Unlock()
	if r, ok := renderers.built[build]; ok && r.key == key {
		return r.program, nil
	}
	// The stamp identifies the last written sources. Unchanged sources keep the
	// requirements and checksums that -mod=mod added to the copy of go.mod.
	stamp := filepath.Join(build, "stamp")
	if old, _ := os.ReadFile(stamp); string(old) != key {
		if err := os.RemoveAll(filepath.Join(build, "gen")); err != nil {
			return "", err
		}
		if err := writeFiles(build, files); err != nil {
			return "", err
		}
		if err := os.WriteFile(stamp, []byte(key), 0o644); err != nil {
			return "", err
		}
	}
	program := filepath.Join(build, "renderer")
	if runtime.GOOS == "windows" {
		program += ".exe"
	}
	// -mod=mod adds the modules that the templates import, as templ, to the
	// copy of go.mod, so the docs module needs to require only docpages.
	args := []string{
		"build",
		"-modfile=" + filepath.Join(build, "go.mod"),
		"-mod=mod",
		"-overlay=" + filepath.Join(build, "overlay.json"),
		"-o", program,
	}
	if raceEnabled() {
		args = append(args, "-race")
	}
	args = append(args, "./"+rendererPackage)
	if out, err := goCommand(modDir, args...); err != nil {
		if msg := goErrors(dir, filepath.Join(build, "main.go"), out, gens); msg != "" {
			return "", errors.New(msg)
		}
		return "", fmt.Errorf("%s: go build: %w\n%s", dir, err, out)
	}
	renderers.built[build] = builtRenderer{key: key, program: program}
	return program, nil
}

// rendererModFile returns the go.mod of mod's renderer. It replaces docpages by
// its source in directory src, or else requires version v of docpages, so that
// the renderer builds with the running docpages.
// A replace of docpages in mod's go.mod gives way.
func rendererModFile(mod *docsModule, src, v string) ([]byte, error) {
	f, err := modfile.Parse(mod.file, mod.goMod, nil)
	if err != nil {
		return nil, err
	}
	var old []module.Version
	for _, r := range f.Replace {
		if r.Old.Path == modulePath {
			old = append(old, r.Old)
		}
	}
	for _, o := range old {
		if err := f.DropReplace(o.Path, o.Version); err != nil {
			return nil, err
		}
	}
	switch {
	case src != "":
		err = f.AddReplace(modulePath, "", src, "")
	case v != "":
		err = f.AddRequire(modulePath, v)
	default:
		return nil, errors.New("building the renderer of the .templ files needs " +
			"the source or the version of docpages; build docpages without -trimpath, " +
			"or from a clean tree")
	}
	if err != nil {
		return nil, err
	}
	f.Cleanup()
	return f.Format()
}

// joinSums returns the lines of go.sum files a and b without repeats.
func joinSums(a, b []byte) []byte {
	seen := make(map[string]bool)
	var r []byte
	for _, data := range [][]byte{a, b} {
		for line := range strings.Lines(string(data)) {
			line = strings.TrimSpace(line)
			if line == "" || seen[line] {
				continue
			}
			seen[line] = true
			r = append(append(r, line...), '\n')
		}
	}
	return r
}

// sourceDir returns the docpages source directory used to build this program,
// from a clone or module cache, or "" if build paths were trimmed.
func sourceDir() string {
	_, file, _, ok := runtime.Caller(0)
	if !ok || !filepath.IsAbs(file) {
		return ""
	}
	dir := filepath.Dir(file)
	data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil || !bytes.HasPrefix(data, []byte("module "+modulePath+"\n")) {
		return ""
	}
	return dir
}

// buildVersion returns the program's docpages version, or "" if go cannot download one.
func buildVersion() string {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return ""
	}
	m := &info.Main
	for _, d := range info.Deps {
		if d.Path == modulePath {
			m = d
		}
	}
	if m.Path != modulePath || m.Replace != nil || m.Version == "" ||
		m.Version == "(devel)" || strings.HasSuffix(m.Version, "+dirty") {
		return ""
	}
	return m.Version
}

// raceEnabled reports whether this program uses the race detector, as CI tests do.
// Matching it lets renderers reuse compiled docpages packages and dependencies;
// a mismatch makes go recompile them.
func raceEnabled() bool {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return false
	}
	race := slices.Contains(info.Settings, debug.BuildSetting{
		Key: "-race", Value: "true",
	})
	return race
}

// rendererDir returns, creating if needed, the build directory for dir in root.
// Each docs directory gets one that another machine user cannot own.
func rendererDir(root, dir string) (string, error) {
	abs := filepath.Join(root, filepath.FromSlash(dir))
	h := sha256.Sum256([]byte(abs))
	build := filepath.Join(rendererRoot(), "docpages-"+hex.EncodeToString(h[:8]))
	return build, os.MkdirAll(build, 0o755)
}

// rendererRoot contains [rendererDir] directories.
// Tests replace it so temporary docs leave no renderers.
var rendererRoot = os.TempDir

// goCommand runs go with args in dir and returns its output.
// It ignores ambient go.work and GOFLAGS, which would change the build.
func goCommand(dir string, args ...string) ([]byte, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=")
	return cmd.CombinedOutput()
}

// goPos matches a go build position and its file,
// which can start with a Windows drive letter.
var goPos = regexp.MustCompile(`^(?:\./)?((?:[A-Za-z]:)?[^\s:]+\.go):(\d+):(\d+): `)

// goErrors maps go build errors in out, run in docs directory dir, to source
// .templ positions from gens, by the path of the generated file, and the
// positions of other files of the docs module to paths from the repository root.
// Errors in mainFile name dir's templ DocpagesMain.
// It returns "" if no file of the docs module has an error.
func goErrors(dir, mainFile string, out []byte, gens map[string]generated) string {
	var lines []string
	found := false
	for line := range strings.Lines(string(out)) {
		line = strings.TrimRight(line, "\n")
		m := goPos.FindStringSubmatchIndex(line)
		if m == nil {
			if !strings.HasPrefix(line, "# ") && line != "" {
				lines = append(lines, line)
			}
			continue
		}
		file, msg := line[m[2]:m[3]], line[m[1]:]
		if file == mainFile {
			found = true
			lines = append(lines, fmt.Sprintf("%s: templ %s(p docpages.Page): %s",
				dir, templateMain, msg))
			continue
		}
		g, ok := gens[file]
		if !ok {
			// Files outside the docs module, as of a dependency, stay as reported.
			if !filepath.IsAbs(file) && !strings.HasPrefix(file, "../") {
				found = true
				line = path.Join(dir, file) + line[m[3]:]
			}
			lines = append(lines, line)
			continue
		}
		found = true
		l, _ := strconv.Atoi(line[m[4]:m[5]])
		c, _ := strconv.Atoi(line[m[6]:m[7]])
		pos := g.source
		if src, ok := g.sourceMap.SourcePositionFromTarget(uint32(l-1), uint32(c-1)); ok {
			pos = fmt.Sprintf("%s:%d:%d", g.source, src.Line+1, src.Col+1)
		}
		lines = append(lines, pos+": "+msg)
	}
	if !found {
		return ""
	}
	return strings.Join(lines, "\n")
}
